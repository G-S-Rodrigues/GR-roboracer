"""Write a track YAML from a map_server map: ``write_track(extract_track())``.

``python -m raceline`` optimizes a raceline and never writes a track; this is
the command that produces a committed ``config/tracks/<name>.yaml`` from an
official map (Porto, #44 part 3). Exit 3 when the extractor refuses, as
``python -m raceline`` does.
"""

from __future__ import annotations

import argparse
import shlex
import sys
from pathlib import Path

from raceline.extract import Pose2D, extract_track, load_map
from raceline.track import write_track


def _parser() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(
        prog="python -m raceline.track_from_map", description=__doc__
    )
    p.add_argument("--map", type=Path, required=True, help="map_server YAML")
    p.add_argument(
        "--start-pose",
        type=float,
        nargs=3,
        required=True,
        metavar=("X", "Y", "YAW"),
    )
    p.add_argument("--direction", choices=("cw", "ccw"), required=True)
    p.add_argument(
        "--walls", choices=("observed", "non_free"), default="observed"
    )
    p.add_argument("--name", required=True)
    p.add_argument("--out", type=Path, required=True)
    p.add_argument("--source-note", default="", help="a header line")
    return p


def main(argv: list[str] | None = None) -> int:
    args = _parser().parse_args(argv)
    grid = load_map(args.map)
    x, y, yaw = args.start_pose
    try:
        track = extract_track(
            grid,
            grid.resolution,
            grid.origin,
            Pose2D(x, y, yaw),
            args.direction,
            name=args.name,
            walls=args.walls,
        )
    except ValueError as err:
        print(f"extractor refused the input: {err}", file=sys.stderr)
        return 3
    command = (
        f"python -m raceline.track_from_map --map {args.map.as_posix()}"
        f" --start-pose {x} {y} {yaw} --direction {args.direction}"
        f" --walls {args.walls} --name {shlex.quote(args.name)}"
    )
    source = f"Generated by: {command}"
    if args.source_note:
        source += f"\n{args.source_note}"
    write_track(track, args.out, source=source)
    return 0


if __name__ == "__main__":
    sys.exit(main())
